"""Auto-rig cut-outs with MediaPipe pose landmarks → overlay/scenes/11_rigs.js (RIGS entries in ORIGINAL cut-out pixels).
usage: auto_rig.py <cutout_dir> <out_js> [names...]   (default: every *.png in the dir)"""
import sys, os, glob, json, numpy as np
from PIL import Image
import mediapipe as mp
from mediapipe.tasks import python as mpt
from mediapipe.tasks.python import vision
M = os.environ.get('BZ_GEN_ROOT', '.') + '/models_sd/mp/pose_heavy.task'
pl = vision.PoseLandmarker.create_from_options(vision.PoseLandmarkerOptions(base_options=mpt.BaseOptions(model_asset_path=M, delegate=mpt.BaseOptions.Delegate.CPU), running_mode=vision.RunningMode.IMAGE))
src, out = sys.argv[1], sys.argv[2]; names = sys.argv[3:] or sorted(os.path.basename(f)[:-4] for f in glob.glob(src + '/*.png'))
rigs, report = {}, []
def mid(a, b): return [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2]
def lerp(a, b, k): return [a[0] + (b[0] - a[0]) * k, a[1] + (b[1] - a[1]) * k]
for n in names:
    im = Image.open(f'{src}/{n}.png').convert('RGBA'); w, h = im.size
    pad = int(h * .1); cv = Image.new('RGB', (w + 2 * pad, h + 2 * pad), (255, 255, 255)); cv.paste(im, (pad, pad), im)
    r = pl.detect(mp.Image(image_format=mp.ImageFormat.SRGB, data=np.array(cv)))
    if not r.pose_landmarks: report.append(f'{n}: NO POSE'); continue
    L = r.pose_landmarks[0]; W, H = cv.size
    P = lambda k: [round(L[k].x * W - pad, 1), round(L[k].y * H - pad, 1)]
    vis = lambda k: L[k].visibility
    nose, eL, eR, mL, mR = P(0), P(2), P(5), P(9), P(10)
    shL, shR, elL, elR, wrL, wrR = P(11), P(12), P(13), P(14), P(15), P(16)
    hpL, hpR, knL, knR, anL, anR = P(23), P(24), P(25), P(26), P(27), P(28)
    hip, sh = mid(hpL, hpR), mid(shL, shR); neck = lerp(sh, mid(eL, eR), .18)
    headTop = lerp(neck, mid(eL, eR), 2.0); ext = lambda a, b, k=.4: lerp(a, b, 1 + k)   # a bone tip extended past the joint (hands, feet)
    bones = [
      {'n': 'hips', 'a': lerp(hip, mid(knL, knR), .35), 'b': hip},
      {'n': 'legL', 'p': 'hips', 'a': hpL, 'b': knL}, {'n': 'shinL', 'p': 'legL', 'a': knL, 'b': ext(knL, anL, .15)},
      {'n': 'legR', 'p': 'hips', 'a': hpR, 'b': knR}, {'n': 'shinR', 'p': 'legR', 'a': knR, 'b': ext(knR, anR, .15)},
      {'n': 'chest', 'p': 'hips', 'a': hip, 'b': sh},
      {'n': 'head', 'p': 'chest', 'a': neck, 'b': headTop},
      {'n': 'armL_up', 'p': 'chest', 'a': shL, 'b': elL}, {'n': 'armL_lo', 'p': 'armL_up', 'a': elL, 'b': ext(elL, wrL, .45)},
      {'n': 'armR_up', 'p': 'chest', 'a': shR, 'b': elR}, {'n': 'armR_lo', 'p': 'armR_up', 'a': elR, 'b': ext(elR, wrR, .45)},
    ]
    ed = abs(eL[0] - eR[0]) or 20; mouth = mid(mL, mR); chin = lerp(nose, mouth, 1.9)
    arr = np.array(im).astype(int); samples = []
    for e in (eL, eR):                                   # skin just under each eye (median of mid-tone pixels)
        x0, y0 = int(e[0] - ed * .25), int(e[1] + ed * .38); patch = arr[max(0, y0):y0 + max(3, int(ed * .18)), max(0, x0):x0 + max(3, int(ed * .5))].reshape(-1, 4)
        patch = patch[(patch[:, 3] > 200)]; lum = patch[:, :3].mean(1); patch = patch[(lum > 45) & (lum < 215)]
        if len(patch): samples.append(np.median(patch[:, :3], 0))
    c = np.mean(samples, 0) if samples else np.array([140, 90, 55])
    skin = '#%02X%02X%02X' % tuple(int(v) for v in c)
    face = {'eyes': [eL, eR], 'eyeR': round(ed * .3, 1), 'eyeRy': round(ed * .22, 1), 'mouth': mouth, 'chin': chin, 'jawW': round(ed * .75, 1), 'jawH': round(ed * .55, 1), 'jawDrop': round(ed * .1, 1), 'skin': skin}
    # which forearm is raised / away from the body gets the talking gesture
    g = []
    for s, sh_, wr in (('R', shR, wrR), ('L', shL, wrL)):
        if wr[1] < sh_[1] + (hip[1] - sh_[1]) * .55: g.append([f'arm{s}_lo', .12, 4.2 if s == 'R' else 3.7])
    rigs['cast/' + n] = {'w': w, 'h': h, 'cell': max(6, round(h / 110)), 'bones': [{k: (v if not isinstance(v, list) else [round(x, 1) for x in v]) for k, v in b.items()} for b in bones],
                         'face': face, 'gesture': g or [['armR_lo', .05, 3.9]], 'vis': {k: round(vis(i), 2) for k, i in (('wrL', 15), ('wrR', 16), ('anL', 27), ('anR', 28))}}
    report.append(f'{n}: ok eyes {eL} {eR} skin {skin} gesture {[x[0] for x in g]}')
js = "'use strict';\n// AUTO-GENERATED by p2/lib/auto_rig.py (MediaPipe pose landmarks on each cut-out). Coordinates in ORIGINAL cut-out pixels.\n"
for k, v in rigs.items(): js += f"RIGS[{json.dumps(k)}] = {json.dumps(v)};\n"
open(out, 'w').write(js); print('\n'.join(report))
